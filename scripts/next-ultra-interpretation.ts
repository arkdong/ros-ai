/** Explicitly directed second and final request under the original max-two/$5 grant.
 * First tool-planning submission failed. This interprets a real local recipe run;
 * it is not a retry, a model-generated experiment, or a reset of accounting.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import dotenv from 'dotenv';
import { Store } from '../src/server/store.js';
import { ExecutionService } from '../src/server/execution.js';
import { ExperimentService } from '../src/server/experiments.js';
import { DEFAULT_MODEL, NebiusAdapter } from '../src/server/providers.js';
const output=resolve('evidence/next-ultra-interpretation.json');
if(!process.argv.includes('--allow-billable'))throw Error('Explicit --allow-billable required for second and final authorized request.');
if(existsSync(output))throw Error('Second request already recorded. No repeat is authorized.');
const first=JSON.parse(readFileSync('evidence/next-ultra-live.json','utf8'));
if(first.outcome!=='failed'||first.usage.length!==1)throw Error('Unexpected prior state; manual review required.');
dotenv.config({path:'.env.local',quiet:true});
const store=new Store(resolve('evidence/next-ultra-data'));
if(store.listUsage().length!==1){store.close();throw Error('Exactly one prior request required; never reset accounting.');}
const execution=new ExecutionService(store,{model:new NebiusAdapter(process.env.NEBIUS_API_KEY,DEFAULT_MODEL),liveAuthorization:{id:'adam-2026-09-21-ultra-two-requests',nebiusUsd:5,tavilyUsd:0,maxRequests:2},maxConcurrent:1,maxOutputTokens:2000,timeoutMs:90000,includeSetupUsage:false});
const local=new ExperimentService(store);
const project=store.getProject(first.project.project.id);
const report:Record<string,unknown>={startedAt:new Date().toISOString(),relationship:'Second and final authorized request. Interpret locally authored recipe output; the first model tool proposal failed and is preserved separately.',priorEvidence:'next-ultra-live.json'};
async function waitRun(id:string){for(let i=0;i<1000;i++){const run=store.getRun(id);if(!['queued','running'].includes(run.status))return run;await new Promise(resolve=>setTimeout(resolve,100));}throw Error('Run timeout; do not retry.');}
try{
 const csv='x,y\n1,3\n2,5\n3,7\n4,9\n';
 const code='x = column("x")\ny = column("y")\nfit = linear_fit(x, y)\nmetric("Slope", fit["slope"])\nmetric("Intercept", fit["intercept"])\nmetric("R squared", fit["r_squared"])\ntable("Y summary", describe(y))\nplot("Observed y", y, x)';
 const preview=local.preview(project.id,{nodeId:'analysis',request:'Execute the build-authored synthetic relationship recipe for independently authorized result interpretation',csv,code,parameters:{}});
 local.decide(preview.run.id,preview.approval.fingerprint,'allow');
 const run=await waitRun(preview.run.id);report.localRunId=run.id;
 if(run.status!=='completed')throw Error(`Real local recipe failed: ${run.error}`);
 const artifacts=store.detail(project.id).artifacts.filter(a=>a.runId===run.id);
 const metrics=artifacts.filter(a=>a.kind==='metric');
 report.observedMetrics=metrics.map(a=>({title:a.title,content:a.content}));
 if(metrics.length!==3||!artifacts.some(a=>a.kind==='plot'))throw Error('Expected actual metrics and plot missing.');
 for(const artifact of artifacts.filter(a=>['metric','table'].includes(a.kind)))store.addInput(project.id,'interpretation',artifact.id,artifact.content);
 const interpreted=await waitRun(execution.startRun(project.id,'interpretation',{request:'Interpret the selected actual local Python outputs. The data were four synthetic observations: x=1,2,3,4; y=3,5,7,9. State measured slope, intercept and R squared, and why a perfect fit here does not establish causality, predictive reliability, or financial performance. Cite the selected inputs and keep the response under 160 words. The local recipe was authored by the build agent, not generated by you.',useSearch:false}).id);
 report.interpretationRunId=interpreted.id;
 if(interpreted.status!=='completed')throw Error(`Ultra interpretation ${interpreted.status}: ${interpreted.error}`);
 report.outcome='completed-text-interpretation-only';
}catch(error){report.outcome='failed';report.error=error instanceof Error?error.message:'Unknown failure';process.exitCode=1;}
finally{
 await execution.shutdown();await local.shutdown();
 report.finishedAt=new Date().toISOString();report.usage=store.listUsage();report.accountedUsd=execution.ledger.accounted('nebius');report.project=store.detail(project.id);
 writeFileSync(output,JSON.stringify(report,null,2)+'\n');store.close();
 console.log(JSON.stringify({outcome:report.outcome,error:report.error,report:output,accountedUsd:report.accountedUsd,requests:(report.usage as unknown[]).length}));
}
