import { chromium, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';

// A dedicated server/data directory is required. Never run against saved user projects.
const base = process.env.ROS_VERIFY_URL || 'http://127.0.0.1:4317';
if (new URL(base).port === '4310') throw new Error('Use an isolated verification server, not the saved-user-data port.');
const api = async (path, body) => {
  const response = await fetch(base + path, body === undefined ? {} : {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
  const value = await response.json(); if (!response.ok) throw new Error(value.error || String(response.status)); return value;
};
const providers = await api('/api/connections');
if (providers.some(provider => provider.configured)) throw new Error('Browser verification requires cloud credentials disabled.');
mkdirSync('evidence/next-build', {recursive:true});
const browser = await chromium.launch();
const page = await browser.newPage({viewport:{width:1512,height:982}});
page.setDefaultTimeout(10000);
const report = {startedAt:new Date().toISOString(),base,checks:[],errors:[]};
page.on('pageerror', error => report.errors.push(error.message));
try {
  await page.goto(base);
  await page.getByTestId('new-project').click();
  const title = `Local browser verification ${Date.now()}`;
  await page.getByLabel('Project name', {exact:true}).fill(title);
  await page.getByTestId('create-project').click();
  await expect(page.getByRole('heading',{name:title,exact:true})).toBeVisible();
  const project = (await api('/api/projects')).find(project => project.title === title);
  report.projectId = project.id;
  const detail = () => api(`/api/projects/${project.id}`);
  const addNode = async (title, kind, inside = false) => {
    if (inside) await page.getByRole('button',{name:'Add topic / activity',exact:true}).click();
    else await page.getByTestId('add-node').click();
    await page.getByRole('button',{name:kind === 'topic' ? 'Topic What you study' : 'Activity What you do',exact:true}).click();
    await page.getByLabel('Name',{exact:true}).fill(title);
    await page.getByRole('button',{name:`Add ${kind}`,exact:true}).click();
    await expect(page.getByTestId('node-title')).toHaveValue(title);
  };
  await addNode('Measurement methods','topic');
  await addNode('Analyze observations','activity');
  const parent = (await detail()).project.canvas.nodes.find(n => n.title === 'Analyze observations');
  await addNode('Distribution questions','topic',true);
  await addNode('Compute descriptive statistics','activity',true);
  const d1 = await detail();
  expect(d1.project.canvas.nodes.filter(n=>!n.parentId).map(n=>n.kind).sort()).toEqual(['activity','topic']);
  expect(d1.project.canvas.nodes.filter(n=>n.parentId === parent.id).map(n=>n.kind).sort()).toEqual(['activity','topic']);
  expect(d1.runs).toHaveLength(0);expect(d1.inputs).toHaveLength(0);expect(d1.project.canvas.connections).toHaveLength(0);
  report.checks.push('Topic and Activity created through the UI at both scopes; no edges, imported inputs or runs required.');
  const left = await page.getByTestId('canvas').boundingBox();
  const right = await page.getByTestId('node-canvas').boundingBox();
  expect(left.x + left.width).toBeLessThanOrEqual(right.x + 2);
  expect(Math.abs(left.width - right.width)).toBeLessThan(8);
  await page.getByLabel('Analysis request',{exact:true}).fill('Summarize observations and plot the values. Keep this draft.');
  await page.getByLabel('Expand node workspace',{exact:true}).click();
  await expect(page.getByTestId('canvas')).not.toBeVisible();
  await page.getByLabel('Restore split view',{exact:true}).click();
  await page.getByLabel('Expand project canvas',{exact:true}).click();
  await expect(page.getByTestId('node-canvas')).not.toBeVisible();
  await page.getByLabel('Restore split view',{exact:true}).click();
  await page.getByTestId('canvas').getByLabel('Zoom in',{exact:true}).click();
  await expect.poll(async()=>page.evaluate(id=>JSON.parse(localStorage.getItem(`ros-ai:viewport:${id}:project`) || '{}').zoom,project.id)).toBeGreaterThan(1);
  const projectView = await page.evaluate(id=>localStorage.getItem(`ros-ai:viewport:${id}:project`),project.id);
  await page.reload();
  await expect(page.getByTestId('node-title')).toHaveValue('Compute descriptive statistics');
  await expect(page.getByLabel('Analysis request',{exact:true})).toHaveValue('Summarize observations and plot the values. Keep this draft.');
  expect(await page.evaluate(id=>localStorage.getItem(`ros-ai:viewport:${id}:project`),project.id)).toBe(projectView);
  report.checks.push('Equal-width left/right canvases, expand/restore both sides, selection and draft survive reload.');
  await page.getByRole('button',{name:'Preview code & request',exact:true}).click();
  await expect(page.getByRole('button',{name:'Allow & run',exact:true})).toBeEnabled();
  const original = await page.getByLabel('Experiment code',{exact:true}).inputValue();
  await page.getByLabel('Experiment code',{exact:true}).fill(original + '\nmetric("Median", median(values))');
  await expect(page.getByRole('button',{name:'Allow & run',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Deny',exact:true}).click();
  const denied = (await detail()).runs[0];
  expect(denied.configuration.approval.status).toBe('denied');
  expect(denied.events.some(event=>event.type === 'process-start')).toBe(false);
  report.checks.push('Changed code disables stale approval; denial records a decision and never starts Python.');
  await page.getByRole('button',{name:'Preview a new attempt',exact:true}).click();
  await page.getByRole('button',{name:'Allow & run',exact:true}).click();
  await expect.poll(async () => (await detail()).runs[0].status).toBe('completed');
  const first = await detail();const firstRun = first.runs[0];
  const metrics = first.artifacts.filter(a=>a.runId === firstRun.id && a.kind === 'metric');
  expect(metrics.map(a=>JSON.parse(a.content).value)).toEqual([25,25]);
  const log = JSON.parse(first.artifacts.find(a=>a.runId === firstRun.id && a.kind === 'log').content);
  expect(log.exitCode).toBe(0);
  await expect(page.locator('.canvas-artifact img')).toHaveCount(1);
  await expect.poll(async()=>page.locator('.canvas-artifact img').evaluateAll(images=>images.every(image=>image.complete&&image.naturalWidth>0))).toBe(true);
  report.checks.push('Real Python computed sample mean and median 25, retained exit-code-0 log, and displayed a generated SVG plot on the node canvas.');
  await page.getByLabel('Experiment code',{exact:true}).fill('values = column("value")\nmetric("Scaled mean", mean(values) * params["scale"])\nplot("Original observations", values)');
  await page.getByLabel('Experiment parameters',{exact:true}).fill('{"scale":2}');
  await page.getByRole('button',{name:'Preview a new attempt',exact:true}).click();
  await page.getByRole('button',{name:'Allow & run',exact:true}).click();
  await expect.poll(async()=>(await detail()).runs[0].status).toBe('completed');
  const revised = await detail();
  expect(revised.runs[0].retryOf).toBe(firstRun.id);
  expect(JSON.parse(revised.artifacts.find(a=>a.runId===revised.runs[0].id&&a.kind==='metric').content).value).toBe(50);
  expect(revised.artifacts.filter(a=>a.runId===firstRun.id)).toEqual(first.artifacts.filter(a=>a.runId===firstRun.id));
  report.checks.push('Revision with captured parameter scale=2 computes 50 in a new linked attempt, preserving every earlier artifact.');
  await expect(page.locator('.canvas-artifact').filter({hasText:'Scaled mean'})).toHaveCount(1);
  await expect(page.locator('.run-status-line > .tag')).toHaveText('completed');
  await page.getByRole('button',{name:'Hide work tools',exact:true}).click();
  await page.getByTestId('node-canvas').getByLabel('Fit canvas',{exact:true}).click();
  await page.waitForTimeout(350); // Finish the explicit Fit canvas animation before visual capture.
  await page.screenshot({path:'evidence/next-build/desktop.png',fullPage:true});
  await page.setViewportSize({width:600,height:850});
  await page.getByRole('button',{name:'Node workspace',exact:true}).click();
  await expect(page.getByTestId('node-canvas')).toBeVisible();
  await expect(page.getByTestId('canvas')).not.toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Open work tools',exact:true}).click();
  await expect(page.getByLabel('Analysis request',{exact:true})).toBeVisible();
  await page.screenshot({path:'evidence/next-build/narrow.png',fullPage:true});
  await page.getByRole('button',{name:'Project canvas',exact:true}).click();
  await expect(page.getByTestId('canvas')).toBeVisible();
  await expect(page.getByTestId('node-canvas')).not.toBeVisible();
  await page.getByLabel('Show sidebar',{exact:true}).click();
  await expect(page.getByLabel('Projects and conversations',{exact:true})).toBeVisible();
  await page.getByLabel('Hide sidebar',{exact:true}).click();
  report.checks.push('600px layout switches canvases deliberately, keeps tools and navigation accessible, with no document overflow.');
  const childTopic=d1.project.canvas.nodes.find(n=>n.title==='Distribution questions');
  const a=await api(`/api/projects/${project.id}/experiments/preview`,{nodeId:parent.id,request:'Auto Research fixture A',csv:'value\n2\n4\n',code:'metric("Independent mean A", mean(column("value")))'});
  const b=await api(`/api/projects/${project.id}/experiments/preview`,{nodeId:childTopic.id,request:'Auto Research fixture B',csv:'value\n10\n20\n',code:'metric("Independent mean B", mean(column("value")))'});
  await page.reload();
  await page.getByRole('button',{name:'Node workspace',exact:true}).click();
  await page.getByRole('button',{name:'Auto Research',exact:true}).click();
  await expect(page.locator('.auto-candidate')).toHaveCount(2);
  for(const checkbox of await page.locator('.auto-candidate input[type=checkbox]').all())await checkbox.check();
  await page.getByRole('button',{name:'Authorize 2 selected attempts',exact:true}).click();
  await expect.poll(async()=>{const d=await detail();return [a.run.id,b.run.id].every(id=>d.runs.find(r=>r.id===id)?.status==='completed');}).toBe(true);
  const groups=await api(`/api/projects/${project.id}/auto-research`);expect(groups[0].status).toBe('completed');expect(groups[0].runIds).toHaveLength(2);
  report.checks.push('Browser Auto Research authorizes two exact pending actions in accepted independent nodes and records separate completed results.');
  expect(await page.locator('body').innerText()).not.toMatch(/investigation/i);
  expect(await api('/api/usage')).toHaveLength(0);
  expect(report.errors).toEqual([]);
  report.status='passed';report.completedAt=new Date().toISOString();
} catch(error) {
  report.status='failed';report.error=error.stack;
  await page.screenshot({path:'evidence/next-build/browser-failure.png',fullPage:true});
  throw error;
} finally {
  writeFileSync('evidence/next-build/browser.json',JSON.stringify(report,null,2)+'\n');
  await browser.close();
}
