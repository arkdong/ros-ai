def draw_distribution(ax, frame, legend=False):
    for group in day_types:
        sample = frame.loc[frame["day_type"].eq(group), "rain_mm"].to_numpy()
        amounts, frequencies = np.unique(sample, return_counts=True)
        cumulative = np.cumsum(frequencies) / len(sample) * 100
        # Aggregate tied zero/rain amounts and retain the 100% plateau to the shared axis limit.
        amounts = np.append(amounts, weather["rain_mm"].max() * 1.04)
        cumulative = np.append(cumulative, 100)
        ax.step(amounts, cumulative, where="post", color=colors[group], linestyle=styles[group], linewidth=2,
                label=f"{group} (n={len(sample)})")
    ax.axvline(1, color="#68737A", linestyle=":", linewidth=1.2)
    ax.set_xlim(0, weather["rain_mm"].max() * 1.04)
    ax.set_ylim(0, 103)
    ax.set_yticks([0, 25, 50, 75, 100], ["0%", "25%", "50%", "75%", "100%"])
    ax.grid(axis="y", color="#E6E9EB", linewidth=0.8)
    ax.set_axisbelow(True)
    if legend:
        ax.legend(loc="lower right", frameon=False, fontsize=11)


