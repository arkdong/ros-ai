assert weather["date"].is_unique and weather["date"].tolist() == expected_dates.tolist(), "Expected every local day of 2024 exactly once."
assert weather["station_id"].eq(240).all(), "This analysis is scoped to KNMI Schiphol station 240."
assert weather["observed_hours"].eq(weather["expected_hours"]).all(), "Incomplete intervals need explicit treatment."
